// Builds every size of the site icon from icons/icon.svg and writes them into
// src/icons.generated.js, which the Worker serves. Needs rsvg-convert (librsvg)
// on the PATH. Run with `pnpm icons` after changing the drawing.
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'

const master = readFileSync(
  new URL('../icons/icon.svg', import.meta.url),
  'utf8',
)

const part = (id) => {
  const match = master.match(new RegExp(`<g id="${id}"[\\s\\S]*?</g>`))
  if (!match) throw new Error(`icons/icon.svg has no <g id="${id}">`)
  return match[0]
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*\n\s*/g, '')
    .replace(` id="${id}"`, '')
}
const fill = master.match(/<rect id="tile"[^>]*fill="([^"]+)"/)?.[1]
if (!fill) throw new Error('icons/icon.svg has no <rect id="tile"> with a fill')
const bird = part('bird')
const letters = part('letters')

const SIZE = 512
/** The drawing is centred on the tile; `scale` shrinks it about that centre. */
const svg = ({ viewBox = `0 0 ${SIZE} ${SIZE}`, radius, scale = 1, parts }) => {
  const [x, y, width, height] = viewBox.split(' ').map(Number)
  const offset = ((1 - scale) * SIZE) / 2
  const transform =
    scale === 1
      ? ''
      : ` transform="translate(${offset} ${offset}) scale(${scale})"`
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"><rect x="${x}" y="${y}" width="${width}" height="${height}"${radius ? ` rx="${radius}"` : ''} fill="${fill}"/><g${transform}>${parts.join('')}</g></svg>\n`
}

// Browser tabs draw the icon at 16 to 32 px, where the lettering is too small
// to read, so the favicon is the bird alone.
const small = svg({ viewBox: '72 45 320 320', radius: 60, parts: [bird] })
const rounded = svg({ radius: 96, parts: [bird, letters] })
// iOS rounds the corners itself and needs an opaque square.
const square = svg({ scale: 0.92, parts: [bird, letters] })
// Android may crop a maskable icon to a circle 80% of its width.
const maskable = svg({ scale: 0.78, parts: [bird, letters] })

const png = (source, size) =>
  execFileSync('rsvg-convert', ['-w', String(size), '-h', String(size)], {
    input: source,
    maxBuffer: 1 << 24,
  })

/** An .ico file is a small directory followed by the PNG images themselves. */
const ico = (images) => {
  const header = Buffer.alloc(6)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(images.length, 4)
  let offset = 6 + 16 * images.length
  const entries = images.map(({ size, data }) => {
    const entry = Buffer.alloc(16)
    entry.writeUInt8(size, 0)
    entry.writeUInt8(size, 1)
    entry.writeUInt16LE(1, 4)
    entry.writeUInt16LE(32, 6)
    entry.writeUInt32LE(data.length, 8)
    entry.writeUInt32LE(offset, 12)
    offset += data.length
    return entry
  })
  return Buffer.concat([header, ...entries, ...images.map(({ data }) => data)])
}

const files = {
  '/favicon.ico': ico(
    [16, 32, 48].map((size) => ({ size, data: png(small, size) })),
  ),
  '/apple-touch-icon.png': png(square, 180),
  '/icon-192.png': png(rounded, 192),
  '/icon-512.png': png(rounded, 512),
  '/icon-maskable-512.png': png(maskable, 512),
}

const lines = [
  '// Generated by scripts/build-icons.mjs from icons/icon.svg. Do not edit.',
  `export const faviconSvg = ${JSON.stringify(small).replaceAll("'", "\\'").replace(/^"|"$/g, "'").replaceAll('\\"', '"')}`,
  '',
  '/** Path to base64 bytes. */',
  'export const iconBase64 = {',
  ...Object.entries(files).map(
    ([path, data]) => `  '${path}':\n    '${data.toString('base64')}',`,
  ),
  '}',
  '',
]
writeFileSync(
  new URL('../src/icons.generated.js', import.meta.url),
  lines.join('\n'),
)
for (const [path, data] of Object.entries(files))
  console.log(`${path}  ${(data.length / 1024).toFixed(1)} KiB`)
